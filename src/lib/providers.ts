export function providersByCategory(category: ProviderCategory | "all") {
  if (category === "all") return PROVIDERS.filter((p) => p.id !== "t3code");
  if (category === "hub") return PROVIDERS.filter((p) => p.category === "hub");
  return PROVIDERS.filter((p) => p.category === category);
}
